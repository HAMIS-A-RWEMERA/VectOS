export function formatTemplate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return Object.entries(vars).reduce((acc, [key, value]) => {
    return acc.replace(new RegExp(`{{\\s*${key}\\s*}}`, 'g'), String(value));
  }, template);
}

export function getNestedTranslation(lang: Language, path: string): string {
  const parts = path.split('.');
  let current: unknown = translations[lang];
  for (const part of parts) {
    if (current && typeof current === 'object' && part in (current as Record<string, unknown>)) {
      current = (current as Record<string, unknown>)[part];
    } else {
      current = undefined;
      break;
    }
  }
  if (typeof current === 'string') return current;

  // Fallback to English if missing
  let fallback: unknown = translations.en;
  for (const part of parts) {
    if (fallback && typeof fallback === 'object' && part in (fallback as Record<string, unknown>)) {
      fallback = (fallback as Record<string, unknown>)[part];
    } else {
      return path;
    }
  }
  return typeof fallback === 'string' ? fallback : path;
}

export function translatePaymentMethod(method: string, lang: Language): string {
  const m = (method || '').toLowerCase();
  if (m === 'cash') return translations[lang].paymentMethods.cash;
  if (m === 'momo') return translations[lang].paymentMethods.momo;
  if (m === 'bank') return translations[lang].paymentMethods.bank;
  if (m === 'credit') return translations[lang].paymentMethods.credit;
  return method;
}

